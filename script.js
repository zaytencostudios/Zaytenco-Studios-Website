const LANGS = Object.keys(I18N);
let lang = "es";
const t = (key) => I18N[lang][key] ?? I18N.es[key] ?? key;

document.documentElement.classList.add("js");
document.getElementById("year").textContent = new Date().getFullYear();

// Header border on scroll
const header = document.querySelector(".site-header");
const onScroll = () => header.classList.toggle("scrolled", window.scrollY > 8);
window.addEventListener("scroll", onScroll, { passive: true });
onScroll();

// Mobile menu
const toggle = document.querySelector(".nav-toggle");
const nav = document.getElementById("nav");
const setMenu = (open) => {
  nav.classList.toggle("open", open);
  toggle.setAttribute("aria-expanded", String(open));
  toggle.setAttribute("aria-label", t(open ? "aria.menuClose" : "aria.menuOpen"));
};
toggle.addEventListener("click", () => setMenu(!nav.classList.contains("open")));
nav.addEventListener("click", (e) => { if (e.target.closest("a")) setMenu(false); });
document.addEventListener("keydown", (e) => { if (e.key === "Escape") setMenu(false); });

// Language switching
const langSwitch = document.querySelector(".lang-switch");
const status = document.getElementById("form-status");
let statusKey = null;

function setLang(next, remember) {
  lang = LANGS.includes(next) ? next : "es";
  document.documentElement.lang = lang;
  document.title = t("meta.title");
  document.querySelector('meta[name="description"]').content = t("meta.description");
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  langSwitch.setAttribute("aria-label", t("aria.lang"));
  langSwitch.querySelectorAll("button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
  toggle.setAttribute("aria-label", t(nav.classList.contains("open") ? "aria.menuClose" : "aria.menuOpen"));
  if (statusKey) status.textContent = t(statusKey);
  if (remember) { try { localStorage.setItem("lang", lang); } catch {} }
}

langSwitch.addEventListener("click", (e) => {
  const btn = e.target.closest("button[data-lang]");
  if (btn) setLang(btn.dataset.lang, true);
});

// Initial language: saved choice, then the browser's language, then Spanish
let saved = null;
try { saved = localStorage.getItem("lang"); } catch {}
const browser = (navigator.languages || [navigator.language || ""])
  .map((l) => l.slice(0, 2).toLowerCase())
  .find((l) => LANGS.includes(l));
setLang(saved || browser || "es", false);

// Reveal on scroll
const reveals = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window) {
  const io = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });
  reveals.forEach((el) => io.observe(el));
} else {
  reveals.forEach((el) => el.classList.add("visible"));
}

// Quote form: validates, then opens the visitor's email app with the request filled in
const form = document.getElementById("quote-form");
const setStatus = (key, cls) => {
  statusKey = key;
  status.className = `form-status ${cls}`;
  status.textContent = t(key);
};

form.addEventListener("submit", (e) => {
  e.preventDefault();
  const fields = [...form.querySelectorAll("input, select, textarea")];
  fields.forEach((f) => f.classList.toggle("invalid", !f.checkValidity()));
  const firstInvalid = fields.find((f) => !f.checkValidity());

  if (firstInvalid) {
    setStatus("form.error", "error");
    firstInvalid.focus();
    return;
  }

  const data = Object.fromEntries(new FormData(form));
  const subject = `${t("mail.subject")} — ${data.servicio}`;
  const body =
    `${t("form.name")}: ${data.nombre}\n` +
    `${t("form.email")}: ${data.email}\n` +
    `${t("form.type")}: ${data.servicio}\n\n` +
    `${data.mensaje}`;

  window.location.href =
    `mailto:${CONTACT_EMAIL}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;

  setStatus("form.ok", "ok");
});

form.addEventListener("input", (e) => e.target.classList.remove("invalid"));
